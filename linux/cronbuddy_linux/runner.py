def shell_quote(value: str) -> str:
    return shlex.quote(value)


def _interpreter_for(path: str) -> str:
    ext = Path(path).suffix.lower()
    return {
        ".py": "/usr/bin/env python3 ",
        ".sh": "/bin/bash ",
        ".bash": "/bin/bash ",
        ".zsh": "/usr/bin/env zsh ",
        ".rb": "/usr/bin/env ruby ",
        ".pl": "/usr/bin/env perl ",
        ".js": "/usr/bin/env node ",
        ".mjs": "/usr/bin/env node ",
    }.get(ext, "")


class ActionScript:
    @staticmethod
    def render(job: Job) -> str:
        safe_name = job.name.replace("\n", " ")
        lines = [
            "#!/bin/bash",
            f"# Generated by CronBuddy for “{safe_name}” ({job.id}).",
            "# Edit the job in CronBuddy; changes here are overwritten.",
        ]
        for key in sorted(job.environment):
            if Job.is_valid_env_name(key):
                lines.append(f"export {key}={shell_quote(job.environment[key])}")
        if job.action.kind == "shell":
            lines.append(job.action.value)
        elif job.action.kind == "script":
            expanded = os.path.expanduser(job.action.value)
            lines.append(f'exec {_interpreter_for(expanded)}{shell_quote(expanded)} "$@"')
        return "\n".join(lines) + "\n"

    @staticmethod
    def write(job: Job, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        tmp.write_text(ActionScript.render(job), encoding="utf-8")
        os.chmod(tmp, 0o755)
        tmp.replace(path)


@dataclass(frozen=True)
class RunRecord:
    job_id: str
    start: float
    end: float
    exit_code: int
    log_file: str
    trigger: str  # "schedule" | "manual"

    @property
    def id(self) -> str:
        return f"{self.job_id}/{self.log_file}"

    @property
    def duration(self) -> float:
        return max(0.0, self.end - self.start)

    @property
    def succeeded(self) -> bool:
        return self.exit_code == 0

    @property
    def started_at(self) -> datetime.datetime:
        return datetime.datetime.fromtimestamp(self.start).astimezone()


class RunHistory:
    @staticmethod
    def stamp(ts: float | None = None) -> str:
        dt = datetime.datetime.fromtimestamp(ts if ts is not None else time.time())
        return dt.strftime("%Y%m%d-%H%M%S")

    @staticmethod
    def load(job_id: str, paths: Paths) -> list[RunRecord]:
        rf = paths.runs_file(job_id)
        if not rf.exists():
            return []
        return RunHistory.parse(rf.read_text(encoding="utf-8", errors="replace"), job_id)

    @staticmethod
    def parse(text: str, job_id: str) -> list[RunRecord]:
        records: list[RunRecord] = []
        for raw in text.splitlines():
            line = raw.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
                records.append(
                    RunRecord(
                        job_id=job_id,
                        start=float(obj["start"]),
                        end=float(obj["end"]),
                        exit_code=int(obj["exit"]),
                        log_file=str(obj["log"]),
                        trigger=str(obj.get("trigger", "schedule")),
                    )
                )
            except Exception:
                continue
        records.sort(key=lambda r: r.start, reverse=True)
        return records

    @staticmethod
    def log_path(record: RunRecord, paths: Paths) -> Path:
        return paths.log_dir(record.job_id) / record.log_file

    @staticmethod
    def log_text(record: RunRecord, paths: Paths) -> str:
        lp = RunHistory.log_path(record, paths)
        if not lp.exists():
            return ""
        return lp.read_text(encoding="utf-8", errors="replace")

    @staticmethod
    def append_line(
        job_id: str,
        start: float,
        end: float,
        exit_code: int,
        log_file: str,
        trigger: str,
        paths: Paths,
    ) -> None:
        log_dir = paths.log_dir(job_id)
        log_dir.mkdir(parents=True, exist_ok=True)
        payload = json.dumps(
            {
                "start": start,
                "end": end,
                "exit": exit_code,
                "log": log_file,
                "trigger": trigger,
            }
        )
        with paths.runs_file(job_id).open("a", encoding="utf-8") as fh:
            fh.write(payload + "\n")

    @staticmethod
    def append(
        job_id: str,
        start: float,
        end: float,
        exit_code: int,
        output: str,
        paths: Paths,
        trigger: str = "manual",
    ) -> RunRecord:
        log_dir = paths.log_dir(job_id)
        log_dir.mkdir(parents=True, exist_ok=True)
        log_file = f"{RunHistory.stamp(start)}-{trigger}-{random.randint(1000, 9999)}.log"
        (log_dir / log_file).write_text(output, encoding="utf-8")
        RunHistory.append_line(job_id, start, end, exit_code, log_file, trigger, paths)
        return RunRecord(
            job_id=job_id,
            start=start,
            end=end,
            exit_code=exit_code,
            log_file=log_file,
            trigger=trigger,
        )

    @staticmethod
    def prune(job_id: str, keep: int, paths: Paths) -> None:
        rf = paths.runs_file(job_id)
        if not rf.exists() or keep < 1:
            return
        lines = [ln for ln in rf.read_text(encoding="utf-8", errors="replace").splitlines() if ln.strip()]
        if len(lines) <= keep:
            return
        dropped = lines[:-keep]
        kept = lines[-keep:]
        log_dir = paths.log_dir(job_id)
        for raw in dropped:
            try:
                obj = json.loads(raw)
                lf = obj.get("log")
                if lf:
                    (log_dir / lf).unlink(missing_ok=True)
            except Exception:
                pass
        tmp = rf.with_suffix(".tmp")
        tmp.write_text("\n".join(kept) + "\n", encoding="utf-8")
        tmp.replace(rf)

    @staticmethod
    def remove_all(job_id: str, paths: Paths) -> None:
        shutil.rmtree(paths.log_dir(job_id), ignore_errors=True)

    @staticmethod
    def running_pid(job_id: str, paths: Paths) -> int | None:
        marker = paths.running_marker(job_id)
        if not marker.exists():
            return None
        try:
            pid = int(marker.read_text(encoding="utf-8").split()[0])
            os.kill(pid, 0)
            return pid
        except Exception:
            marker.unlink(missing_ok=True)
            return None


def send_notification(title: str, body: str, urgency: str = "normal") -> None:
    """Best-effort desktop notification via notify-send."""
    if os.environ.get("CRONBUDDY_HOME"):
        return
    notify_bin = shutil.which("notify-send")
    if not notify_bin:
        return
    try:
        subprocess.run(
            [notify_bin, "-u", urgency, "-a", "CronBuddy", title, body[:240]],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=3,
            check=False,
        )
    except Exception:
        pass


class ScheduledRun:
    @staticmethod
    def run(
        job_id: str,
        paths: Paths,
        trigger: str = "schedule",
        job: Job | None = None,
        keep_runs: int = 50,
    ) -> int:
        log_dir = paths.log_dir(job_id)
        log_dir.mkdir(parents=True, exist_ok=True)
        start = time.time()
        log_file = f"{RunHistory.stamp(start)}-{os.getpid()}.log"
        log_path = log_dir / log_file
        marker = paths.running_marker(job_id)
        marker.write_text(f"{os.getpid()} {start}\n", encoding="utf-8")

        action = paths.action_script(job_id)
        code = 126
        try:
            if not action.exists():
                log_path.write_text(
                    f"CronBuddy: no action script at {action}\n", encoding="utf-8"
                )
                code = 127
            else:
                env = os.environ.copy()
                env["PATH"] = f"{paths.default_path}:{env.get('PATH', '')}"
                with log_path.open("w", encoding="utf-8") as fh:
                    proc = subprocess.run(
                        ["/bin/bash", str(action)],
                        stdin=subprocess.DEVNULL,
                        stdout=fh,
                        stderr=subprocess.STDOUT,
                        env=env,
                        check=False,
                    )
                    code = proc.returncode
        finally:
            marker.unlink(missing_ok=True)

        end = time.time()
        RunHistory.append_line(job_id, start, end, code, log_file, trigger, paths)
        RunHistory.prune(job_id, keep_runs, paths)

        if job is not None:
            preview = ""
            try:
                lines = [ln.strip() for ln in log_path.read_text(encoding="utf-8", errors="replace").splitlines() if ln.strip()]
                if lines:
                    preview = lines[-1]
            except Exception:
                pass
            if code != 0 and job.notify_on_failure:
                send_notification(
                    f"CronBuddy — {job.name} failed (exit {code})",
                    preview or "Check the job log for details.",
                    urgency="critical",
                )
            elif code == 0 and job.notify_on_success:
                send_notification(
                    f"CronBuddy — {job.name} finished",
                    preview or "Completed successfully.",
                    urgency="normal",
                )
        return code

    @staticmethod
    def run_streaming(
        action_script: Path,
        paths: Paths,
        on_chunk: Callable[[str], None] | None = None,
    ) -> tuple[int, str, float, float]:
        """Run an action script while streaming output line-by-line."""
        start = time.time()
        env = os.environ.copy()
        env["PATH"] = f"{paths.default_path}:{env.get('PATH', '')}"
        chunks: list[str] = []
        proc = subprocess.Popen(
            ["/bin/bash", str(action_script)],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            errors="replace",
            env=env,
        )
        assert proc.stdout is not None
        for line in proc.stdout:
            chunks.append(line)
            if on_chunk:
                on_chunk(line)
        code = proc.wait()
        end = time.time()
        return code, "".join(chunks), start, end
